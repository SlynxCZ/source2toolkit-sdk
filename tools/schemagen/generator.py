# ---------------------------------------------------------------------------
# Field categorisation helpers
# ---------------------------------------------------------------------------

def _is_pointer_field(field: SchemaField) -> bool:
    return (
        field.type.category == SchemaTypeCategory.FixedArray
        or field.type.name == "CUtlStringToken"
    )


def _virtual_return_type(field: SchemaField) -> str:
    # Globally qualify declared enum/class types to prevent MSVC from confusing
    # the method name with the return type when they share the same identifier
    # (e.g. virtual BloodType& BloodType() would shadow the BloodType type).
    cpp_type = field.type.cpp_type_name
    if field.type.category in (SchemaTypeCategory.DeclaredEnum, SchemaTypeCategory.DeclaredClass):
        cpp_type = f"::{cpp_type}"
    if _is_pointer_field(field):
        return f"{cpp_type}*"
    return f"{cpp_type}&"


# ---------------------------------------------------------------------------
# Effective parent resolution
# ---------------------------------------------------------------------------

def _is_entity_class(class_name: str) -> bool:
    return len(class_name) >= 2 and class_name[0] == "C" and class_name[1].isupper()


def _interface_name(class_name: str) -> str:
    if _is_entity_class(class_name):
        return "I" + class_name[1:]
    return "I" + class_name


def _effective_parent(
    schema_class: SchemaClass,
    generated: set[str],
) -> Optional[str]:
    p = schema_class.parent
    if p is None or p in HARD_SKIP_CLASSES or p not in generated:
        # Special case: CEntityInstance is in HARD_SKIP_CLASSES but we generate IEntityInstance
        if p == "CEntityInstance":
            return "CEntityInstance"
        return None
    if not _is_entity_class(p):
        return None
    return p


