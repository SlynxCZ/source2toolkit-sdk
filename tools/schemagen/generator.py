# ---------------------------------------------------------------------------
# Manual method virtual declaration helper
# ---------------------------------------------------------------------------

def _manual_method_virtual_decl(m: dict) -> str:
    const = " const" if m["is_const"] else ""
    params = ", ".join(m["params_with_defaults"])
    return f"    virtual {m['return_type']} {m['name']}({params}){const} = 0;"


# ---------------------------------------------------------------------------
# Interface header generation
# ---------------------------------------------------------------------------

def _collect_interface_refs(
    t: SchemaFieldType,
    all_enums: dict[str, SchemaEnum],
    enum_includes: set[str],
    forwards: set[str],
) -> None:
    if t.category == SchemaTypeCategory.DeclaredEnum:
        if t.name not in HARD_SKIP_ENUMS:
            enum_includes.add(t.name)
    elif t.category == SchemaTypeCategory.DeclaredClass:
        if t.name not in HARD_SKIP_CLASSES and '*' not in t.name:
            forwards.add(t.name)
    if t.inner is not None:
        _collect_interface_refs(t.inner, all_enums, enum_includes, forwards)


def write_interface_header(
    class_name: str,
    schema_class: SchemaClass,
    all_enums: dict[str, SchemaEnum],
    all_classes: dict[str, SchemaClass],
    generated: set[str],
) -> str:
    """Generate IFoo.h - a pure virtual interface for class_name."""

    i_class_name = _interface_name(class_name)
    parent = _effective_parent(schema_class, generated)
    i_parent_name = _interface_name(parent) if parent else None

    enum_includes: set[str] = set()
    forwards: set[str] = set()

    # Collect from schema fields
    for f in schema_class.fields:
        if f.type.category == SchemaTypeCategory.Bitfield:
            continue
        if _field_has_ignored_wildcard(f.type):
            continue
        if contains_ignored_type(f.type):
            continue
        _collect_interface_refs(f.type, all_enums, enum_includes, forwards)

    # Collect from manual methods: scan strings for known schema class/enum names
    for method_str in MANUAL_METHODS.get(class_name, []):
        for enum_name in all_enums:
            if enum_name not in HARD_SKIP_ENUMS and enum_name in method_str:
                enum_includes.add(enum_name)
        for cls_name in all_classes:
            if cls_name not in HARD_SKIP_CLASSES and cls_name in method_str:
                forwards.add(cls_name)
        # Forward-declare IXxx interface types referenced in method signatures.
        for m in re.finditer(r'\bI([A-Z][A-Za-z_0-9]*)\b', method_str):
            forwards.add("I" + m.group(1))

    # Extra forward declarations for non-schema types
    for fwd in _EXTRA_IFACE_FWD_DECLS.get(class_name, []):
        forwards.add(fwd)

    forwards.discard(class_name)

    guard = make_header_guard(i_class_name)
    lines = [
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#pragma once",
        "",
    ]

    lines += _IFACE_SDK_INCLUDES

    # Extra includes (e.g. <functional> for std::function)
    extra_incs = _EXTRA_IFACE_INCLUDES.get(class_name, [])
    if extra_incs:
        for inc in extra_incs:
            lines.append(inc)
    lines.append("")

    if i_parent_name:
        if parent == "CEntityInstance":
            lines.append('#include "IEntityInstance.h"')
        else:
            lines.append(f'#include "{i_parent_name}.h"')
        lines.append("")
    else:
        # Root interface classes have no parent that would pull in IEntityInstance.h,
        # but GetOriginal() calls reinterpret_cast<IEntityInstance*>(this)->GetOriginal() — include it explicitly.
        lines.append('#include "IEntityInstance.h"')
        lines.append("")

    for e in sorted(enum_includes):
        lines.append(f'#include "../enums/{sanitise_type_name(e)}.h"')
    if enum_includes:
        lines.append("")

    # Forward-declare the underlying CXxx class for GetOriginal()
    forwards.add(class_name)

    for fwd in sorted(forwards):
        lines.append(f"class {fwd};")
    if forwards:
        lines.append("")

    if i_parent_name:
        lines.append(f"class {i_class_name} : public virtual {i_parent_name}")
    else:
        lines.append(f"class {i_class_name}")

    lines += [
        "{",
        "public:",
        f"    virtual ~{i_class_name}() = default;",
    ]
    # Root classes (no IEntityInstance in hierarchy) declare GetOriginal() as a pure virtual.
    # Child classes inherit it from IEntityInstance — the impl overrides it with the
    # covariant CXxx* return type where both types are complete, so no declaration needed here.
    if not i_parent_name:
        lines.append(f"    virtual {class_name}* GetOriginal() const = 0;")
    lines.append("")

    # Schema field pure virtuals
    _skips = FIELD_SKIPS.get(class_name, set())
    for f in schema_class.fields:
        if f.name in _skips:
            continue
        if f.type.category == SchemaTypeCategory.Bitfield:
            continue
        if _field_has_ignored_wildcard(f.type):
            continue
        if contains_ignored_type(f.type):
            continue

        method_name = to_pascal_case(f.name)
        ret = _virtual_return_type(f)
        lines.append(f"    virtual {ret} {method_name}() = 0;")
        if not _is_pointer_field(f):
            lines.append(f"    virtual void {method_name}Updated() = 0;")

    # Process MANUAL_METHODS: pair each doc comment with the method that follows it.
    # - Instance methods (parseable) -> emit as pure virtuals with their doc comment above.
    # - Static / template methods  -> pass through verbatim with their doc comment above.
    # - Trailing / orphan comments -> pass through as-is.
    virtual_block: list[str] = []
    static_block:  list[str] = []
    pending_comment: Optional[str] = None

    for entry in MANUAL_METHODS.get(class_name, []):
        stripped = entry.strip()
        if stripped.startswith("///"):
            pending_comment = entry
            continue

        is_static_or_template = (
            stripped.startswith("static ") or stripped.startswith("template")
        )

        if is_static_or_template:
            if pending_comment is not None:
                static_block.append(f"    {pending_comment}")
                pending_comment = None
            static_block.append(f"    {entry}")
        else:
            parsed = _parse_manual_method(entry)
            if parsed is not None:
                if pending_comment is not None:
                    virtual_block.append(f"    {pending_comment}")
                    pending_comment = None
                virtual_block.append(_manual_method_virtual_decl(parsed))
            else:
                # Inline-body instance method or unparseable — skip.
                pending_comment = None

    if pending_comment is not None:
        static_block.append(f"    {pending_comment}")

    if virtual_block:
        lines.append("")
        lines += virtual_block

    if static_block:
        lines.append("")
        lines += static_block

    # FromOriginal – static factory; declaration only (defined in CXxx.cpp).
    lines.append(f"    static {i_class_name}* FromOriginal({class_name}* p);")

    lines.append("};")
    lines.append("")
    lines.append(f"#endif // {guard}")
    lines.append("")
    return LICENSE_HEADER + "\r\n".join(lines)


